void* zircon_game_manager::CreateSurface(
	kotek::core::ktkMainManager* p_main_manager,
	void* p_instance,
	const void* p_callbacks
)
{
	KOTEK_ASSERT(p_main_manager, "must be valid");

	auto* p_engine_config = p_main_manager->Get_EngineConfig();

	KOTEK_ASSERT(
		p_engine_config,
		"you must initialize engine config, something is wrong"
	);

	bool is_gl_initialized =
		p_engine_config->GetRendererVersionEnum() >=
			kotek::core::eEngineSupportedRenderer::
				kOpenGL_1_0 ||
		p_engine_config->GetRendererVersionEnum() <=
			kotek::core::eEngineSupportedRenderer::
				kOpenGL_Latest;
	bool is_vk_initialized =
		p_engine_config->GetRendererVersionEnum() >=
			kotek::core::eEngineSupportedRenderer::
				kVulkan_1_0 ||
		p_engine_config->GetRendererVersionEnum() <=
			kotek::core::eEngineSupportedRenderer::
				kVulkan_Latest;
	bool is_dx_initialized =
		p_engine_config->GetRendererVersionEnum() >=
			kotek::core::eEngineSupportedRenderer::kDirectX_7 ||
		p_engine_config->GetRendererVersionEnum() <=
			kotek::core::eEngineSupportedRenderer::
				kDirectX_Latest;
	bool is_gles_initialized =
		p_engine_config->GetRendererVersionEnum() >=
			kotek::core::eEngineSupportedRenderer::
				kOpenGLES_1 ||
		p_engine_config->GetRendererVersionEnum() <=
			kotek::core::eEngineSupportedRenderer::
				kOpenGLES_Latest;

	int how_many_is_initialized{};

	if (is_gl_initialized)
		++how_many_is_initialized;
	if (is_vk_initialized)
		++how_many_is_initialized;
	if (is_dx_initialized)
		++how_many_is_initialized;
	if (is_gles_initialized)
		++how_many_is_initialized;

	KOTEK_ASSERT(
		how_many_is_initialized == 1,
		"you have more than one initialized renderer version "
		"enum! It "
		"means that some code breaks logic and it sets one of "
		"enum to "
		"valid value, but it is not right, because you must "
		"have only "
		"on initialized renderer formally."
	);

	// TODO: think about DX12 here
	if (is_vk_initialized)
	{
		KOTEK_ASSERT(
			false,
			"vulkan backend was removed (2026-07-22), bgfx is the only raster backend"
		);
	}

	return nullptr;
}

