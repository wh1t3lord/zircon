void zircon_game_manager::Initialize_Renderer(void) noexcept
{
	// the console window instance is owned by kotek.core.window (registered
	// into the main manager at module init)
	this->m_p_window_console =
		static_cast<kotek::core::ktkWindowConsole*>(
			this->m_p_main_manager->Get_WindowConsole());

	KOTEK_ASSERT(this->m_p_window_console,
		"kotek.core.window must register a window console instance before the "
		"game manager initializes");

	ktk_filesystem_path path;

	this->m_p_main_manager->GetFileSystem()->Make_Path(
		path, kotek::core::eFolderIndex::kFolderIndex_DataUser
	);

	//	auto path =
	// this->m_p_main_manager->GetFileSystem()->GetFolderByEnum(
	//		kotek::core::eFolderIndex::kFolderIndex_DataUser);

	path /= KOTEK_USE_LOG_OUTPUT_FILE_NAME;

	int imgui_height = 0;

#ifdef KOTEK_USE_SDK_IMGUI
	// todo: think how to get imgui's height
	imgui_height = 19;
#endif

	if (this->m_p_main_manager->Get_Logger())
	{
		this->m_p_main_manager->Get_Logger()->Flush_All();
	}

	this->m_p_window_console->Initialize(
		this->m_p_main_manager->Get_WindowManager()
			->Get_ActiveWindow(),
		this->m_p_main_manager->GetFileSystem(),
		this->m_p_main_manager->Get_Input(),
		this->m_p_main_manager->Get_Logger(),
		this->m_p_console,
		imgui_height,
		path
	);

	auto* p_engine_config =
		this->m_p_main_manager->Get_EngineConfig();

	KOTEK_ASSERT(
		p_engine_config,
		"you must initialize engine config for using this "
		"method"
	);

	// TODO: add initialization with appropriate gl version of
	// we have the 4.6 for example we have to initialize with
	// according version
	if (p_engine_config->IsFeatureEnabled(
			kotek::core::eEngineFeatureRenderer::
				kEngine_Feature_Renderer_OpenGL_Latest
		) ||
	    p_engine_config->IsFeatureEnabled(
			kotek::core::eEngineFeatureRenderer::
				kEngine_Feature_Renderer_OpenGL_SpecifiedByUser
		))
	{
		switch (p_engine_config->GetRendererVersionEnum())
		{
		default:
			KOTEK_ASSERT(false, "not supported");
			break;
		}
	}
	else if (p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_Vulkan_Latest
			 ) ||
	         p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_Vulkan_SpecifiedByUser
			 ))
	{
		KOTEK_ASSERT(
			false,
			"vulkan backend was removed (2026-07-22), bgfx is the only raster backend"
		);
	}
	else if (p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_DirectX_Latest
			 ) ||
	         p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_DirectX_SpecifiedByUser
			 ))
	{
#ifdef KOTEK_USE_RENDER_NRI
		// task K11/Z5 phase 1: the DirectX slot is the NRI backend
		this->m_renderers.p_nri =
			new zircon_renderer_nri(this->m_p_main_manager);

		this->m_renderers.p_nri->Initialize();

		this->m_p_current_renderer = this->m_renderers.p_nri;
#else
		KOTEK_ASSERT(false, "not supported");
#endif
	}
	else if (p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_OpenGLES_Latest
			 ) ||
	         p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_OpenGLES_SpecifiedByUser
			 ))
	{
		switch (p_engine_config->GetRendererVersionEnum())
		{
		case kotek::core::eEngineSupportedRenderer::
			kOpenGLES_3_0:
		case kotek::core::eEngineSupportedRenderer::
			kOpenGLES_3_1:
		case kotek::core::eEngineSupportedRenderer::
			kOpenGLES_3_2:
		default:
		{
			bool isBGFX = p_engine_config->IsFeatureEnabled(
				kotek::core::eEngineFeatureRendererVendor::kBGFX
			);

			if (isBGFX)
			{
				this->m_renderers.p_bgfx =
					new zircon_renderer_bgfx(
						this->m_p_main_manager
					);

				this->m_renderers.p_bgfx->Initialize(
					this->m_p_window_console,
					this->m_p_console,
					this->m_p_session_game_manager,
					this->m_p_session_editor_manager
				);

				// the pass-library seam (task Z3 P3a): the manager
				// installs create/destroy into the renderer — the
				// hot-swappable passes/zircon.render.passes.bgfx.dll
				// when the graphics_development feature is on in a
				// ZIRCON_GRAPHICS_DEVELOPMENT build, the
				// statically-linked passlib functions otherwise
				this->m_renderers.p_bgfx->initialize_pass_library(
					this->m_p_config->is_feature_enabled(
						eZirconSDKFeatures::
							kSDK_Feature_GraphicsDevelopment),
					&zircon_passlib_create, &zircon_passlib_destroy,
					&zircon_passlib_get_count, &zircon_passlib_get_name);

				this->m_p_current_renderer =
					this->m_renderers.p_bgfx;
			}
			else
			{
				KOTEK_ASSERT(
					false,
					"gles3 backend was removed (2026-07-22), bgfx is the only raster backend"
				);
			}

			break;
		}
		}
	}
	else if (p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_Software
			 ))
	{
		KOTEK_ASSERT(false, "not implemented yet");
	}
	else
	{
		KOTEK_ASSERT(
			false,
			"can't be, but engine contains undefined render "
			"feature!!!! Render Feature Name: {}",
			this->m_p_main_manager->Get_EngineConfig()
				->GetRenderName()
		);
	}

	KOTEK_MESSAGE(
		"Initialized Renderer: [{}]",
		this->m_p_current_renderer->Get_Name()
	);
}

void zircon_game_manager::Destroy_Renderer(void) noexcept
{
	if (this->m_p_window_console)
	{
		this->m_p_window_console->Shutdown();
	}

	auto* p_engine_config =
		this->m_p_main_manager->Get_EngineConfig();

	if (p_engine_config->IsFeatureEnabled(
			kotek::core::eEngineFeatureRenderer::
				kEngine_Feature_Renderer_OpenGL_Latest
		) ||
	    p_engine_config->IsFeatureEnabled(
			kotek::core::eEngineFeatureRenderer::
				kEngine_Feature_Renderer_OpenGL_SpecifiedByUser
		))
	{
		switch (p_engine_config->GetRendererVersionEnum())
		{
		default:
			KOTEK_ASSERT(false, "not supported");
			break;
		}
	}
	else if (p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_Vulkan_Latest
			 ) ||
	         p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_Vulkan_SpecifiedByUser
			 ))
	{
		KOTEK_ASSERT(
			false,
			"vulkan backend was removed (2026-07-22), bgfx is the only raster backend"
		);
	}
	else if (p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_DirectX_Latest
			 ) ||
	         p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_DirectX_SpecifiedByUser
			 ))
	{
#ifdef KOTEK_USE_RENDER_NRI
		KOTEK_ASSERT(
			this->m_renderers.p_nri,
			"must be valid nri renderer!"
		);

		delete this->m_renderers.p_nri;
		this->m_renderers.p_nri = nullptr;

		// task Z5 phase 2 (P4): the game manager owns the NRI frame
		// passes — destroy them inside the passlib (the cross-CRT rule)
		// only after the renderer that drove them is gone
		for (kotek::ktk::size_t pass_index = 0;
			 pass_index < this->m_frame_passes_nri.size(); ++pass_index)
		{
			zircon_nri_passlib_destroy(
				this->m_frame_passes_nri[pass_index]);
		}

		this->m_frame_passes_nri.clear();
#else
		KOTEK_ASSERT(false, "not implemented yet");
#endif
	}
	else if (p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_OpenGLES_Latest
			 ) ||
	         p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_OpenGLES_SpecifiedByUser
			 ))
	{
		bool isBGFX = p_engine_config->IsFeatureEnabled(
			kotek::core::eEngineFeatureRendererVendor::kBGFX
		);

		if (isBGFX)
		{
			KOTEK_ASSERT(
				this->m_renderers.p_bgfx,
				"must be valid bgfx renderer!"
			);

			delete this->m_renderers.p_bgfx;
			this->m_renderers.p_bgfx = nullptr;
		}
		else
		{
			KOTEK_ASSERT(
				false,
				"gles3 backend was removed (2026-07-22), bgfx is the only raster backend"
			);
		}
	}
	else if (p_engine_config->IsFeatureEnabled(
				 kotek::core::eEngineFeatureRenderer::
					 kEngine_Feature_Renderer_Software
			 ))
	{
		KOTEK_ASSERT(false, "not implemented yet");
	}
	else
	{
		KOTEK_ASSERT(
			false,
			"you must have initialized or (it is undefined and "
			"not "
			"supported flag) for eEngineFeatureRenderer field "
			"in "
			"engine config. It means that we can't understand "
			"what was "
			"your renderer and can't deallocate resources. "
			"Something "
			"is wrong if your initialize_renderer method "
			"calling was "
			"successful, because it means that something broke "
			"your "
			"code and you got invalid enum but it was supposed "
			"that "
			"everything would be fine and you would obtain "
			"your "
			"version for what you initialized before in "
			"initialize_renderer method respectively"
		);
	}

	this->m_p_current_renderer = nullptr;
}

