const zircon_imgui_elements_t&
zircon_game_manager::get_ui_imgui_elements()
{
	if (!this->m_p_current_session)
	{
		KOTEK_ASSERT(
			false,
			"early calling? Otherwise set current session!"
		);
		return empty_ui_elements;
	}

	if (this->m_p_current_session)
	{
		eZirconSessionType session_type =
			this->m_p_current_session->get_type();

		switch (session_type)
		{
		case eZirconSessionType::kEditor:
		{
			zircon_session_editor* p_session =
				dynamic_cast<zircon_session_editor*>(
					this->m_p_current_session
				);

			KOTEK_ASSERT(
				p_session,
				"are you sure that you didn't mistaken return "
				"type of "
				"::get_type method?"
			);

			if (p_session)
			{
				return p_session->get_imgui_ui_elements();
			}

			break;
		}
		case eZirconSessionType::kGame:
		{
			zircon_session_game* p_session =
				dynamic_cast<zircon_session_game*>(
					this->m_p_current_session
				);

			KOTEK_ASSERT(
				p_session,
				"are you sure that you didn't mistaken return "
				"type of "
				"::get_type method?"
			);

			if (p_session)
			{
				return p_session->get_imgui_ui_elements();
			}

			break;
		}
		default:
		{
			KOTEK_ASSERT(
				false,
				"unknown session type report to developers! "
				"Otherwise memory "
				"corruptuion"
			);
			return empty_ui_elements;
		}
		}
	}

	return empty_ui_elements;
}

#ifdef KOTEK_DEBUG
	#ifdef KOTEK_USE_TESTS_RUNTIME

		#include <gtest/gtest.h>
		#include <crtdbg.h>

void zircon_game_manager::run_unit_tests()
{
	// route CRT asserts (KOTEK_ASSERT, pico ECS_ASSERT) to stderr
	// instead of the modal CRT dialog, otherwise a failed assert
	// hangs the whole test run waiting for a user click
	_CrtSetReportMode(_CRT_ASSERT, _CRTDBG_MODE_FILE);
	_CrtSetReportFile(_CRT_ASSERT, _CRTDBG_FILE_STDERR);
	_CrtSetReportMode(_CRT_ERROR, _CRTDBG_MODE_FILE);
	_CrtSetReportFile(_CRT_ERROR, _CRTDBG_FILE_STDERR);

	// test output must survive an abort: block-buffered pipes lose
	// everything that was not flushed
	setvbuf(stdout, nullptr, _IONBF, 0);
	setvbuf(stderr, nullptr, _IONBF, 0);

	fprintf(stderr, "[tests]: entering run_unit_tests\n");

	// tests are a static-linkage feature: test files instantiate concrete
	// classes from kotek feature modules, which is forbidden in PLUGIN mode
	// (no link edges between plugin dlls), so their registrars are not
	// compiled there
#if !defined(KOTEK_USE_LINKAGE_PLUGIN)
		#ifdef KOTEK_USE_SDK_IMGUI
	zircon_register_unit_tests_editor();
		#endif

	zircon_register_unit_tests_game();
#endif

	KOTEK_MESSAGE("//unit testing\\\\");
	int argc =
		this->m_p_main_manager->Get_EngineConfig()->GetARGC();
	testing::FLAGS_gtest_catch_exceptions = true;
	testing::FLAGS_gtest_break_on_failure = true;
	testing::FLAGS_gtest_print_time = true;
	testing::FLAGS_gtest_throw_on_failure = true;
	testing::InitGoogleTest(
		&argc,
		this->m_p_main_manager->Get_EngineConfig()->GetARGV()
	);

#ifdef ZIRCON_USE_GRAPHICS_DEVELOPMENT
	// the graphics-development export surface (the PRE_LINK-generated
	// .def whose entries act as /INCLUDE) can pull kotek module test
	// objects into game.ktk through shared COMDATs — their suites then
	// self-register into THIS registry too. They already run in
	// kotek.exe's own run; executing them here as well would double-run
	// non-rerun-safe tests (the plugin-override test's never-unloaded
	// double dll locks its own re-copy). This runner is zircon's, so it
	// runs zircon's suites only.
	testing::GTEST_FLAG(filter) = "Zircon_*";
#endif

	auto status = RUN_ALL_TESTS();
	fprintf(
		stderr, "[tests]: RUN_ALL_TESTS finished with %d\n", status
	);
	KOTEK_ASSERT(status == 0, "unit tests failed!");
	KOTEK_MESSAGE("//unit testing\\\\");
}
	#endif
#endif
