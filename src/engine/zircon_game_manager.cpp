void zircon_game_manager::initialize_render_graph(
	kotek::uint8_t render_graph_id,
	kotek::core::ktkMainManager* p_main_manager,
	kotek::core::ktkIRenderResourceManager*
		p_render_resource_manager
) noexcept
{
	if (this->is_render_graph_initialized(render_graph_id))
	{
#ifdef KOTEK_DEBUG
		KOTEK_MESSAGE_WARNING(
			"render graph#{} was initialized!", render_graph_id
		);
#endif
		return;
	}

	kotek::core::ktkIFrameworkConfig* p_config =
		this->m_p_main_manager->Get_EngineConfig();

	KOTEK_ASSERT(
		p_config, "framework config wasn't initialized!"
	);

	kotek::core::eEngineSupportedRenderer version =
		static_cast<kotek::core::eEngineSupportedRenderer>(
			p_config->GetRendererVersion()
		);

	switch (version)
	{
	case kotek::core::eEngineSupportedRenderer::kOpenGLES_3_0:
	case kotek::core::eEngineSupportedRenderer::kOpenGLES_3_1:
	case kotek::core::eEngineSupportedRenderer::kOpenGLES_3_2:
	{
		bool isBGFX = p_config->IsFeatureEnabled(
			kotek::core::eEngineFeatureRendererVendor::kBGFX
		);

		if (isBGFX)
		{
			KOTEK_ASSERT(
				this->m_renderers.p_bgfx,
				"renderer for gles wasn't initialized (bgfx)"
			);

			if (this->m_renderers.p_bgfx)
			{
				this->m_renderers.p_bgfx
					->initialize_render_graph(
						render_graph_id,
						p_main_manager,
						p_render_resource_manager,
						this->m_p_session_game_manager,
						this->m_p_session_editor_manager
					);
			}
		}
		else
		{
			KOTEK_ASSERT(
				false,
				"gles3 backend was removed (2026-07-22), bgfx is the only raster backend"
			);
		}

		break;
	}
	case kotek::core::eEngineSupportedRenderer::kDirectX_Latest:
	{
		// NRI phase 1 (task K11/Z5): no render graphs on this backend
		KOTEK_MESSAGE_WARNING(
			"[nri] initialize_render_graph is not supported by the NRI "
			"backend in phase 1 (render_graph_id {})",
			render_graph_id
		);
		break;
	}
	default:
	{
		KOTEK_ASSERT(false, "unsupported renderer");
		break;
	}
	}
}

bool zircon_game_manager::is_render_graph_initialized(
	kotek::uint8_t render_graph_id
)
{
	bool result{};

	kotek::core::ktkIFrameworkConfig* p_config =
		this->m_p_main_manager->Get_EngineConfig();

	KOTEK_ASSERT(
		p_config, "framework config wasn't initialized!"
	);

	kotek::core::eEngineSupportedRenderer version =
		static_cast<kotek::core::eEngineSupportedRenderer>(
			p_config->GetRendererVersion()
		);

	switch (version)
	{
	case kotek::core::eEngineSupportedRenderer::kOpenGLES_3_0:
	case kotek::core::eEngineSupportedRenderer::kOpenGLES_3_1:
	case kotek::core::eEngineSupportedRenderer::kOpenGLES_3_2:
	{
		bool isBGFX = p_config->IsFeatureEnabled(
			kotek::core::eEngineFeatureRendererVendor::kBGFX
		);

		if (isBGFX)
		{
			KOTEK_ASSERT(
				this->m_renderers.p_bgfx,
				"renderer for gles wasn't initialized (bgfx)"
			);

			if (this->m_renderers.p_bgfx)
			{
				result = this->m_renderers.p_bgfx
							 ->is_render_graph_initialized(
								 render_graph_id
							 );
			}
		}
		else
		{
			KOTEK_ASSERT(
				false,
				"gles3 backend was removed (2026-07-22), bgfx is the only raster backend"
			);
		}

		break;
	}
	case kotek::core::eEngineSupportedRenderer::kDirectX_Latest:
	{
		// NRI phase 1 (task K11/Z5): no render graphs on this backend,
		// so nothing graph-shaped is ever initialized
		result = false;
		break;
	}
	default:
	{
		KOTEK_ASSERT(false, "unsupported renderer");
		break;
	}
	}

	return result;
}

