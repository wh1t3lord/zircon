	auto p_command_initialize_world =
		[this](kotek::static_cstring_t<
			   ZIRCON_DEF_WORLD_NAME_MAX_STRING_LENGTH>
	               world_name) -> bool
	{

#ifdef KOTEK_USE_SDK_IMGUI
		KOTEK_ASSERT(
			this->m_p_session_editor_manager,
			"must be initialized otherwise early calling!"
		);
#endif

		KOTEK_ASSERT(
			this->m_p_session_game_manager,
			"must be initialized otherwise early calling!"
		);

		KOTEK_ASSERT(
			this->m_p_current_session,
			"must be initialize otherwise early calling or you "
			"forgot to call "
			"set session!"
		);

		if (!this->m_p_current_session)
		{
			KOTEK_MESSAGE_WARNING(
				"you forgot to set current session, because "
				"it is nullptr we can't initialize world!"
			);
			return false;
		}

		if (this->m_p_current_session->get_type() ==
		    eZirconSessionType::kEditor)
		{
			zircon_session_editor* p_session_editor =
				static_cast<zircon_session_editor*>(
					this->m_p_current_session
				);

			if (p_session_editor->get_world() == nullptr)
			{
				KOTEK_MESSAGE_WARNING(
					"your editor session [{}] doesn't have a "
					"valid world, you "
					"have to "
					"set world to session before calling this "
					"command!",
					this->m_p_current_session->get_session_name(
					)
				);

				return false;
			}

			if (p_session_editor->get_world()->is_initialized())
			{
				KOTEK_MESSAGE_WARNING(
					"your editor session [{}] contains "
					"already initialized world!",
					p_session_editor->get_session_name()
				);

				return true;
			}

			p_session_editor->get_world()->initialize(
				world_name,
				this->m_p_config,
				this->m_p_console,
				this->m_p_main_manager->Get_Input(),
				this->m_p_factory
			);

			KOTEK_MESSAGE(
				"initialized world [{}]:{} for editor session!",
				p_session_editor->get_world()->get_name(),
				p_session_editor->get_world()->get_id()
			);
		}
		else if (this->m_p_current_session->get_type() ==
		         eZirconSessionType::kGame)
		{
			zircon_session_game* p_session_game =
				static_cast<zircon_session_game*>(
					this->m_p_current_session
				);

			if (p_session_game->get_world() == nullptr)
			{
				KOTEK_MESSAGE_WARNING(
					"your game session [{}] doesn't have a "
					"valid world, you "
					"have to "
					"set world to session before calling this "
					"command!",
					this->m_p_current_session->get_session_name(
					)
				);

				return false;
			}

			if (p_session_game->get_world()->is_initialized())
			{
				KOTEK_MESSAGE_WARNING(
					"your game session [{}] contains already "
					"initialized world!",
					p_session_game->get_session_name()
				);
				return true;
			}

			p_session_game->get_world()->initialize(
				world_name,
				this->m_p_config,
				this->m_p_console,
				this->m_p_main_manager->Get_Input(),
				this->m_p_factory
			);

			KOTEK_MESSAGE(
				"initialized world [{}]:{} for game session!",
				p_session_game->get_world()->get_name(),
				p_session_game->get_world()->get_id()
			);
		}
		else
		{
			KOTEK_MESSAGE_WARNING(
				"you have undefine session type we can't "
				"execute command "
				"properly due to fact that we don't know to "
				"which session type "
				"to cast! Session: [{}]",
				this->m_p_current_session->get_session_name()
			);
			return false;
		}

		return true;
	};

